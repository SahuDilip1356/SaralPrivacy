// Data movements between nodes. Every edge answers: what moves, why, how, does
// it create a copy, and does it leave firm control.
//
// `external` must equal "either endpoint is client / vendor / government /
// third-party / public" - validatePack enforces consistency with the node
// boundaries, so it cannot drift.
//
// TWO THINGS ABOUT THIS SECTOR SHOW UP IN THE EDGES AND NOWHERE ELSE IN THE
// SERIES:
//
//  1. Data flows TO THE OTHER SIDE on purpose. `ex-serve-opposing`,
//     `au-serve-opposing` and `cl-set-to-opposing` are not failures - they are
//     the workflow. What is in the set is the only control there is.
//  2. Data flows INTO A PUBLIC RECORD by design. `au-record-public` is the one
//     edge on this map with no possible reversal, which is why its stage carries
//     hotspot #1.
//
// Any edge touching a model-gated node MUST carry the same gate, or validatePack
// fails with "source/target absent for model X".

