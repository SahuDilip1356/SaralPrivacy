// Data movements between nodes. Every edge answers: what moves, why, how, does
// it create a copy, and does it leave the business's control.
//
// `external` must equal "either endpoint is client / vendor / government /
// third-party / public" - validatePack enforces consistency with the node
// boundaries, so it cannot drift.
//
// FOUR THINGS ABOUT THIS SECTOR SHOW UP IN THE EDGES AND NOWHERE ELSE IN THE
// SERIES:
//
//  1. THE BODY IS PHOTOGRAPHED, THEN PUBLISHED. `pm-progress-shot`,
//     `pm-into-library`, `pm-before-after` and above all `pm-publish` trace the
//     path from a phone camera in a changing area to an Instagram feed. Every
//     other map moves records; this one turns a customer's body into the
//     business's advertisement.
//  2. THE STAFF MEMBER'S OWN PHONE IS THE CHANNEL, SIX TIMES OVER.
//     `eb-staff-phone-booking`, `hd-form-photo`, `ac-assess-photo`,
//     `pm-progress-shot`, `ml-followup-personal` and `ra-staff-departs` all
//     land on the same unmanaged handset at six different stages. That is not
//     sloppiness in the model; it is how the trade actually runs - and
//     `ra-staff-departs` is the client list leaving with the person.
//  3. HEALTH DATA IS COLLECTED BY A FRONT DESK, NOT A CLINIC. `hd-declaration`,
//     `hd-desk-reads`, `hd-typed-in` and `sp-caution-group` show a medical
//     declaration travelling through reception hands and staff group chats.
//  4. THE PEOPLE WHO NEVER BOUGHT ANYTHING ARE MOVED TOO. `rm-guardian-sign`,
//     `rm-emergency-entry`, `bp-gift-voucher` and `eb-corporate-list` carry
//     guardians, emergency contacts, voucher senders and employees on an HR
//     list - none of whom was ever given a notice.
//
// Any edge touching a model-gated node MUST carry a gate that is a subset of
// BOTH endpoints' models, or validatePack fails with "source/target absent for
// model X". There are deliberately NO gym-only-to-salon-only edges: the three
// models meet only through the shared core, which is what keeps them three
// genuinely different journeys rather than one journey with switches.

