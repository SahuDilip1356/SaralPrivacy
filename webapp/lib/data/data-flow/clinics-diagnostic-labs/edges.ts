// Data movements between nodes. Every edge answers: what moves, why, how, does
// it create a copy, and does it leave the practice's control.
//
// `external` must equal "either endpoint is client/vendor/government/third-party/
// public" - validatePack enforces this against the node boundaries, so a family
// member receiving a report reads as an external transfer, which is exactly the
// point this sector needs to make.
//
// An edge's `businessModels` must be a subset of BOTH endpoints' models. Edges
// touching a consultation-only or laboratory-only node are gated to the same
// models as that node, so a movement never references a system hidden in the
// selected operating model.
//
// Every stage carries at least one edge in EVERY model that shows it - otherwise
// that stage renders with no data moving through it.

