// Data movements between nodes. Every edge answers: what moves, why, how, does
// it create a copy, and does it leave the business's control.
//
// `external` must equal "either endpoint is client / vendor / government /
// third-party / public" - validatePack enforces consistency with the node
// boundaries, so it cannot drift.
//
// THREE THINGS ABOUT THIS SECTOR SHOW UP IN THE EDGES AND NOWHERE ELSE IN THE
// SERIES:
//
//  1. The business is often NOT the first collector. `enq-ota` and
//     `res-create-profile` run the other way round from every other map: the
//     guest is captured by a platform the business does not own, under a notice
//     the business did not write, and only then copied inward. A recruitment
//     agency, a clinic and a law firm all meet the data principal first.
//  2. A GOVERNMENT IDENTITY DOCUMENT MOVES AS A ROUTINE CONDITION OF SERVICE.
//     `id-whatsapp`, `ci-scan`, `sup-airline` and `anc-visa-submit` are not
//     failures - a passport genuinely has to reach a carrier and an immigration
//     authority. What has no justification is the eleven other places the same
//     image ends up on the way.
//  3. The journey RECORDS THE PERSON'S BODY IN SPACE. `mon-wifi`, `mon-cctv`,
//     `mon-live-location` and `mon-key-issue` create a record of where a named
//     individual was, hour by hour, that no other map in this series generates -
//     and it keeps being generated after the reason for it has ended.
//
// Any edge touching a model-gated node MUST carry the same gate, or validatePack
// fails with "source/target absent for model X". There are deliberately NO
// hotel-node-to-travel-node edges: the two halves meet only through the shared
// core, which is what keeps `integrated` a genuine superset rather than a
// merge of two unrelated journeys.

