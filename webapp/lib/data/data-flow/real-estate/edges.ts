// Data movements between nodes. Every edge answers: what moves, why, how, does
// it create a copy, and does it leave firm control.
//
// `external` must equal "either endpoint is client / vendor / government /
// third-party / public" - validatePack enforces consistency with the node
// boundaries, so it cannot drift.
//
// TWO THINGS ABOUT THIS SECTOR SHOW UP IN THE EDGES AND NOWHERE ELSE IN THE
// SERIES:
//
//  1. The client's identity is BROADCAST TO COMPETITORS on purpose.
//     `mat-post-group`, `mat-sheet-share` and `sv-cobroker-attends` are not
//     failures - they are how stock is found. A law firm shares with one
//     adversary; a property firm posts to forty independent agents at once, and
//     nobody can list who received it.
//  2. The database OUTLIVES the deal by design. `arc-crm`, `arc-marketing` and
//     `com-marketing` move a finished client back into the top of the funnel,
//     because an old lead is genuinely worth money in this business. That is
//     why the archive stage carries a hotspot rather than a footnote.
//
// Any edge touching a model-gated node MUST carry the same gate, or validatePack
// fails with "source/target absent for model X".

