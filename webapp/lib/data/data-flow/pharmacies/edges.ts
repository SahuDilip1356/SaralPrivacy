// Data movements between nodes. Every edge answers: what moves, why, how, does
// it create a copy, and does it leave the pharmacy's control.
//
// `external` must equal "either endpoint is client / vendor / government /
// third-party / public" - validatePack enforces consistency with the node
// boundaries, so it cannot drift.
//
// THREE THINGS ABOUT THIS SECTOR SHOW UP IN THE EDGES AND NOWHERE ELSE IN THE
// SERIES:
//
//  1. THE PRODUCT LEAVES CARRYING THE RECORD. `dis-label-package`,
//     `del-counter`, `del-family` and `del-agg` are the sector's signature:
//     the medicine goes out with the molecule on the strip, the patient's name
//     on the label and the itemised invoice attached, and it is handed to
//     whoever is at the door. Every other map in this series can only leak a
//     record; this one delivers it.
//  2. A HEALTH INFERENCE IS CREATED WITHOUT ANYONE COLLECTING ONE. `cr-create`,
//     `rm-history` and `cbp-model` build a chronic-condition profile out of
//     nothing but billing rows and dates. Nobody wrote down a diagnosis and
//     nobody had to.
//  3. THE INTAKE CHANNEL IS SOMEBODY'S OWN PHONE. `enq-whatsapp`,
//     `rx-photo-whatsapp`, `bp-screenshot` and `cp-photo-whatsapp` all land in
//     the same personal thread, which is why one node carries four separate
//     collections at four separate stages. That is not sloppiness in the model;
//     it is how the trade actually runs.
//
// Any edge touching a model-gated node MUST carry a gate that is a subset of
// BOTH endpoints' models, or validatePack fails with "source/target absent for
// model X". Note the intersections that are easy to get wrong here: a
// COUNTER node talking to a WAREHOUSED node resolves to `chain-hospital` alone,
// and a RETAIL node talking to anything resolves to `retail` alone.
//
// There are deliberately NO retail-only-to-online-only edges: the three models
// meet only through the shared core, which is what keeps them three genuinely
// different journeys rather than one journey with switches.

