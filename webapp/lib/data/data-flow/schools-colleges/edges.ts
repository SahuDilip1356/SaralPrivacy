// Data movements between nodes. Every edge answers: what moves, why, how, does
// it create a copy, and does it leave the institution's control.
//
// `external` must equal "either endpoint is client/vendor/government/third-party/
// public" - validatePack enforces this against the node boundaries. Note what
// that means here: a report card reaching a PARENT is not external, because for
// a minor the guardian stands in the child's shoes - but the same record
// reaching an employer, a board or an ad platform is.
//
// An edge's `businessModels` must be a subset of BOTH endpoints' models. Edges
// touching a transport, hostel, placement, proctoring or group-analytics node
// are gated to the same models as that node, so a movement never references a
// system hidden in the selected operating model.
//
// Every stage carries at least one edge in EVERY model that shows it - otherwise
// that stage renders with nothing moving through it.

