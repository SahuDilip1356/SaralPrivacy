// Data movements between nodes. Every edge answers: what moves, why, how, does
// it create a copy, and does it leave the company's control.
//
// `external` must equal "either endpoint is client / vendor / government /
// third-party / public" - validatePack enforces consistency with the node
// boundaries, so it cannot drift.
//
// FOUR THINGS ABOUT THIS SECTOR SHOW UP IN THE EDGES AND NOWHERE ELSE IN THE
// SERIES:
//
//  1. THE DATA IS COLLECTED IN ORDER TO BE JUDGED. `rd8-master-in`,
//     `rd8-device-in`, `rd8-contacts-in`, `rd8-bureau-in`, `rd8-stmt-in` and
//     `rd8-field-in` all converge on one node, and what comes out -
//     `rd8-decide`, `rd8-outcome-customer` - is a new fact about the person.
//     Every other map in this series moves records around. This one turns them
//     into a verdict and then ships the verdict onward.
//  2. THE VERDICT IS SHIPPED TO PEOPLE THE CUSTOMER CANNOT NAME. `pd-route`,
//     `pd-lenders`, `pd-partner-direct` and `pd-decision-share` send the file
//     and the score to institutions that each keep their own copy - including
//     the ones that decline. `pd-register` is the only thing that makes any of
//     it answerable later.
//  3. THE PEOPLE WHO NEVER APPLIED ARE MOVED TOO. `rp-coapplicant`,
//     `rp-references`, `rd-contacts` and above all `ar-refs-to-agency` and
//     `ar-contacts-to-collections` carry data about people who have no
//     relationship with the business at all, into the least controlled place it
//     has.
//  4. THE CHANNEL IS SOMEBODY'S OWN PHONE, FOUR TIMES OVER. `la-dsa-phone`,
//     `kyc-photo-phone`, `la-whatsapp-followup` and `ar-agent-phone` all land on
//     the same unmanaged handset at four different stages, which is why one node
//     carries four separate movements. That is not sloppiness in the model; it
//     is how the trade actually runs.
//
// Any edge touching a model-gated node MUST carry a gate that is a subset of
// BOTH endpoints' models, or validatePack fails with "source/target absent for
// model X". The intersections that are easy to get wrong here: a DIGITAL node
// talking to a LENDING node resolves to `digital-lending` alone, and a LENDING
// node talking to an NBFC node resolves to `nbfc` alone.
//
// There are deliberately NO payments-only-to-lending-only edges: the three
// models meet only through the shared core, which is what keeps them three
// genuinely different journeys rather than one journey with switches.

