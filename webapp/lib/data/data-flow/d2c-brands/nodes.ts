// runs both a storefront and marketplaces - so it renders the full union, while
// own-website and marketplace-first each render their honest, smaller picture.
//
// Staff devices span every stage: customer data sits on phones and laptops for
// the whole lifecycle, so it is drawn as a place, not as a journey step.

