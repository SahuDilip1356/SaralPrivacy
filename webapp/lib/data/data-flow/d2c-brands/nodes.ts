//   - no `businessModels`      -> shared core: own-website, marketplace AND omnichannel
//   - ["website","omnichannel"] -> own-storefront surfaces (own checkout, replay, gateway)
//   - ["marketplace","omnichannel"] -> platform surfaces (seller portal, settlements, FBA)
//   - ["omnichannel"]           -> retail + unified-profile surfaces (POS, CDP, clienteling)
